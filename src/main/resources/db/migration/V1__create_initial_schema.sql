CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    password_hash VARCHAR(255),
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    role VARCHAR(255) DEFAULT 'USER',
    status VARCHAR(255) DEFAULT 'ACTIVE',
    failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    currency VARCHAR(3),
    status VARCHAR(255) DEFAULT 'ACTIVE',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    balance NUMERIC(28,12) DEFAULT 0,
    CONSTRAINT fk_wallets_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(255),
    user_id BIGINT NOT NULL,
    from_wallet_id BIGINT NOT NULL,
    to_wallet_id BIGINT NOT NULL,
    currency VARCHAR(255),
    amount NUMERIC(28,12),
    converted_amount NUMERIC(28,12),
    fx_rate NUMERIC(28,12),
    fee NUMERIC(28,12) DEFAULT 0,
    status VARCHAR(255) DEFAULT 'PENDING',
    error_message VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_transfers_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_transfers_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_transfers_from_wallet FOREIGN KEY (from_wallet_id) REFERENCES wallets (id),
    CONSTRAINT fk_transfers_to_wallet FOREIGN KEY (to_wallet_id) REFERENCES wallets (id)
);

CREATE TABLE payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(255),
    user_id BIGINT NOT NULL,
    wallet_id BIGINT NOT NULL,
    type VARCHAR(255),
    amount NUMERIC(28,12),
    currency VARCHAR(255),
    status VARCHAR(255) DEFAULT 'PENDING',
    external_payment_id VARCHAR(255),
    failure_reason VARCHAR(255),
    attempts INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_payment_transactions_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_payment_transactions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_payment_transactions_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id)
);

CREATE TABLE ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL,
    transfer_id BIGINT,
    payment_id BIGINT,
    entry_type VARCHAR(255),
    amount NUMERIC(28,12),
    balance_after NUMERIC(28,12),
    currency VARCHAR(255),
    description VARCHAR(255),
    created_at TIMESTAMP(6) WITH TIME ZONE,
    operation_key VARCHAR(255),
    CONSTRAINT uk_ledger_entries_wallet_operation UNIQUE (wallet_id, operation_key),
    CONSTRAINT fk_ledger_entries_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id),
    CONSTRAINT fk_ledger_entries_transfer FOREIGN KEY (transfer_id) REFERENCES transfers (id),
    CONSTRAINT fk_ledger_entries_payment FOREIGN KEY (payment_id) REFERENCES payment_transactions (id)
);

CREATE TABLE exchange_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_currency VARCHAR(255),
    quote_currency VARCHAR(255),
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    rate NUMERIC(28,12)
);

CREATE TABLE outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(255),
    aggregate_id VARCHAR(255),
    event_type VARCHAR(255),
    status VARCHAR(255) DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    payload JSONB
);
